"""Declarative base and metadata conventions.

The explicit naming convention is not cosmetic: without it, Alembic
autogenerate emits constraints with backend-generated names that cannot be
referenced in a later downgrade or ALTER. Fixing that after migrations exist in
history is painful, so it is fixed here at the start.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata = MetaData(naming_convention=NAMING_CONVENTION)


class Base(DeclarativeBase):
    """Base class for all RevTrace ORM models."""

    metadata = metadata
